using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace EngineNS.LeanCLR.Generator
{
    /// <summary>
    /// 生成代码文本。代理遵循 FLeanClrIntrinsicCall 的原始缓冲区 ABI：
    /// 每个参数一个 8 字节槽，实例方法槽 0 为 VM this；参数缓冲与返回缓冲可能重叠，先读完全部参数再写返回值。
    /// </summary>
    internal static class LeanClrEmitter
    {
        private const string Header = "// <auto-generated/>";
        private const string StubSymbol = "TITAN_LEANCLR_STUB";
        private const string CallType = "global::EngineNS.LeanCLR.FLeanClrIntrinsicCall";
        private const string DispatcherType = "global::EngineNS.LeanCLR.TtLeanClrIntrinsicDispatcher";
        private const string HostBinding = "global::EngineNS.LeanCLR.TtLeanClrHostBinding";
        private const string HostTypeList = "global::System.Collections.Generic.List<global::System.Collections.Generic.KeyValuePair<global::System.Type, string>>";
        private const string HostTypePair = "global::System.Collections.Generic.KeyValuePair<global::System.Type, string>";
        private const int SlotSize = 8;

        public static string EmitStubs(IReadOnlyList<ClassModel> classes)
        {
            var sb = new StringBuilder();
            sb.AppendLine(Header);
            sb.AppendLine($"#if {StubSymbol}");
            // 派生桩会隐藏父类桩的同名方法
            sb.AppendLine("#pragma warning disable CS0108, CS0114");
            foreach (var group in classes.GroupBy(c => c.Namespace))
            {
                var hasNamespace = group.Key.Length > 0;
                var indent = hasNamespace ? "    " : string.Empty;
                sb.AppendLine();
                if (hasNamespace)
                {
                    sb.AppendLine($"namespace {group.Key}");
                    sb.AppendLine("{");
                }
                foreach (var cls in group)
                {
                    var name = TtLeanClrGenerator.EscapeIdentifier(cls.Name);
                    sb.AppendLine($"{indent}public class {name} : {cls.StubBaseName}");
                    sb.AppendLine($"{indent}{{");
                    sb.AppendLine($"{indent}    protected {name}() {{ }}");
                    foreach (var method in cls.Methods)
                    {
                        var modifiers = method.IsStatic ? "public static" : "public";
                        var parameters = string.Join(", ", method.Parameters.Select(p => $"{p.Type.CSharpName} {TtLeanClrGenerator.EscapeIdentifier(p.Name)}"));
                        sb.AppendLine($"{indent}    {modifiers} {method.ReturnType.CSharpName} {TtLeanClrGenerator.EscapeIdentifier(method.Name)}({parameters}) {{ throw null; }}");
                    }
                    sb.AppendLine($"{indent}}}");
                }
                if (hasNamespace)
                    sb.AppendLine("}");
            }
            sb.AppendLine("#endif");
            return sb.ToString();
        }

        public static string EmitRegistry(IReadOnlyList<ClassModel> classes, string assemblyName)
        {
            var registryName = "TtLeanClrRegistry_" + ToSafeIdentifier(assemblyName);
            var methods = classes.SelectMany(c => c.Methods.Select(m => (Class: c, Method: m))).ToList();

            var sb = new StringBuilder();
            sb.AppendLine(Header);
            sb.AppendLine($"#if !{StubSymbol}");
            sb.AppendLine("#pragma warning disable");
            sb.AppendLine($"[assembly: global::EngineNS.LeanCLR.TtLeanClrRegistryAttribute(typeof(global::EngineNS.LeanCLR.Generated.{registryName}))]");
            sb.AppendLine();
            sb.AppendLine("namespace EngineNS.LeanCLR.Generated");
            sb.AppendLine("{");
            sb.AppendLine($"    internal sealed unsafe class {registryName} : global::EngineNS.LeanCLR.ITtLeanClrRegistry");
            sb.AppendLine("    {");
            sb.AppendLine($"        public string StubAssemblyName => \"{assemblyName}.LeanClrStub\";");
            sb.AppendLine();
            sb.AppendLine("        private static readonly string[] sSignatures = new string[]");
            sb.AppendLine("        {");
            foreach (var (_, method) in methods)
                sb.AppendLine($"            \"{method.Signature}\",");
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine($"        private static readonly {DispatcherType}.FIntrinsicHandler[] sHandlers = new {DispatcherType}.FIntrinsicHandler[]");
            sb.AppendLine("        {");
            for (var i = 0; i < methods.Count; ++i)
                sb.AppendLine($"            Proxy_{i},");
            sb.AppendLine("        };");
            sb.AppendLine();
            sb.AppendLine($"        public void Register({DispatcherType} dispatcher)");
            sb.AppendLine("        {");
            sb.AppendLine("            for (var i = 0; i < sSignatures.Length; ++i)");
            sb.AppendLine("                dispatcher.Register(global::VNameString.FromString(sSignatures[i]), sHandlers[i]);");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        public void Unregister({DispatcherType} dispatcher)");
            sb.AppendLine("        {");
            sb.AppendLine("            for (var i = 0; i < sSignatures.Length; ++i)");
            sb.AppendLine("                dispatcher.Unregister(global::VNameString.FromString(sSignatures[i]));");
            sb.AppendLine("        }");
            sb.AppendLine();
            sb.AppendLine($"        public void CollectHostTypes({HostTypeList} hostTypes)");
            sb.AppendLine("        {");
            foreach (var cls in classes)
                sb.AppendLine($"            hostTypes.Add(new {HostTypePair}(typeof({cls.CSharpName}), \"{cls.FullName}\"));");
            sb.AppendLine("        }");

            for (var i = 0; i < methods.Count; ++i)
            {
                sb.AppendLine();
                EmitProxy(sb, i, methods[i].Class, methods[i].Method);
            }
            sb.AppendLine("    }");
            sb.AppendLine("}");
            sb.AppendLine("#endif");
            return sb.ToString();
        }

        private static void EmitProxy(StringBuilder sb, int index, ClassModel cls, MethodModel method)
        {
            sb.AppendLine($"        // {method.Signature}");
            sb.AppendLine($"        private static bool Proxy_{index}({CallType}* call)");
            sb.AppendLine("        {");
            sb.AppendLine("            var args = (byte*)call->GetArgumentBuffer();");
            var slot = 0;
            if (!method.IsStatic)
            {
                sb.AppendLine($"            var self = {HostBinding}.ResolveHost<{cls.CSharpName}>(*(void**)args);");
                sb.AppendLine("            if (self == null)");
                sb.AppendLine("                return false;");
                ++slot;
            }
            for (var i = 0; i < method.Parameters.Count; ++i, ++slot)
                sb.AppendLine($"            var a{i} = {ReadArgument(method.Parameters[i].Type, $"args + {slot * SlotSize}")};");

            var arguments = Enumerable.Range(0, method.Parameters.Count).Select(i => $"a{i}").ToList();
            string invocation;
            if (method.NeedsAccessor)
            {
                arguments.Insert(0, method.IsStatic ? "null" : "self");
                invocation = $"Accessor_{index}({string.Join(", ", arguments)})";
            }
            else
            {
                var target = method.IsStatic ? cls.CSharpName : "self";
                invocation = $"{target}.{TtLeanClrGenerator.EscapeIdentifier(method.Name)}({string.Join(", ", arguments)})";
            }

            if (method.ReturnType.Kind == ETypeKind.Void)
            {
                sb.AppendLine($"            {invocation};");
            }
            else
            {
                sb.AppendLine($"            var result = {invocation};");
                sb.AppendLine($"            {WriteReturn(method.ReturnType, "call->GetReturnBuffer()", "result")};");
            }
            sb.AppendLine("            return true;");
            sb.AppendLine("        }");

            if (method.NeedsAccessor)
            {
                var kind = method.IsStatic ? "StaticMethod" : "Method";
                var parameters = new List<string> { $"{cls.CSharpName} self" };
                parameters.AddRange(method.Parameters.Select((p, i) => $"{p.Type.CSharpName} a{i}"));
                sb.AppendLine();
                sb.AppendLine($"        [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.{kind}, Name = \"{method.Name}\")]");
                sb.AppendLine($"        private static extern {method.ReturnType.CSharpName} Accessor_{index}({string.Join(", ", parameters)});");
            }
        }

        private static string ReadArgument(TypeModel type, string address)
        {
            switch (type.Kind)
            {
                case ETypeKind.Boolean:
                    return $"*(byte*)({address}) != 0";
                case ETypeKind.HostObject:
                    return $"{HostBinding}.ResolveHost<{type.CSharpName}>(*(void**)({address}))";
                case ETypeKind.String:
                    return $"{HostBinding}.ReadString(*(void**)({address}))";
                case ETypeKind.Enum:
                    return $"({type.CSharpName})(*({type.UnderlyingCSharpName}*)({address}))";
                case ETypeKind.BlittableStruct:
                    return $"*({type.CSharpName}*)({address})";
                default:
                    return $"*({type.CSharpName}*)({address})";
            }
        }

        private static string WriteReturn(TypeModel type, string buffer, string value)
        {
            switch (type.Kind)
            {
                // VM 以 int32 读取小于 4 字节的返回值，必须写满 4 字节
                case ETypeKind.Boolean:
                    return $"*(int*){buffer} = {value} ? 1 : 0";
                case ETypeKind.Char:
                case ETypeKind.SByte:
                case ETypeKind.Byte:
                case ETypeKind.Int16:
                case ETypeKind.UInt16:
                    return $"*(int*){buffer} = {value}";
                case ETypeKind.HostObject:
                    return $"*(void**){buffer} = {HostBinding}.GetVmObjectPointer({value})";
                case ETypeKind.String:
                    return $"*(void**){buffer} = {HostBinding}.NewVmString({value})";
                case ETypeKind.Enum:
                    // enum 返回值写满 int32（底层类型可能 <4 字节）
                    return $"*(int*){buffer} = (int){value}";
                case ETypeKind.BlittableStruct:
                    return $"*({type.CSharpName}*){buffer} = {value}";
                default:
                    return $"*({type.CSharpName}*){buffer} = {value}";
            }
        }

        private static string ToSafeIdentifier(string name)
        {
            var sb = new StringBuilder(name.Length);
            foreach (var c in name)
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');
            if (sb.Length == 0 || char.IsDigit(sb[0]))
                sb.Insert(0, '_');
            return sb.ToString();
        }
    }
}
