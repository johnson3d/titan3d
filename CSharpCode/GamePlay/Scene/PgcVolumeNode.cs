        public bool IsGeneratedNode(TtNode node)
        {
            for (var current = node; current != null && !ReferenceEquals(current, this);
                current = current.Parent)
            {
                if (current.HasStyle(ENodeStyles.PgcGenerated))
                    return true;
            }
            return false;
        }

